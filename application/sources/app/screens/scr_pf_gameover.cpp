void view_scr_pf_gameover() {
	uint16_t score = pf_get_game_score();
	view_render.clear();
	view_render.drawBitmap((LCD_WIDTH - PF_GAMEVOVER_ICON_WIDTH)/2, 5, gameover_icon_bitmap, PF_GAMEVOVER_ICON_WIDTH, PF_GAMEVOVER_ICON_HEIGHT, WHITE);
	view_render.drawBitmap (25, 40, head_wolf_icon_bitmap, PF_HEAD_WOLF_ICON_WIDTH, PF_HEAD_WOLF_ICON_HEIGHT, WHITE);
	view_render.setTextSize(2);
	view_render.setCursor(55, 41);
	view_render.print(" X ");
	view_render.println(score);
}

void scr_pf_gameover_handle(ak_msg_t *msg) {
	switch (msg->sig) {
		case SCREEN_ENTRY: {
			APP_DBG_SIG("PF_GAMEPLAY\n");
			timer_set(AC_TASK_DISPLAY_ID,AC_DISPLAY_GAMEPLAY_UPDATE,AC_DISPLAY_GAMEPLAY_UPDATE_INTERVAL_MS,TIMER_PERIODIC);
			break;
		}
		case AC_DISPLAY_GAMEPLAY_UPDATE: {
			scr_mng_invalidate();
			break;
		}
		case AC_DISPLAY_BUTON_MODE_PRESSED: 
		case AC_DISPLAY_BUTON_UP_PRESSED: 
		case AC_DISPLAY_BUTON_DOWN_PRESSED: {
			SCREEN_TRAN(scr_pf_menu_handle, &scr_pf_menu);
			break;
		}
		default:
			break;
	}
}