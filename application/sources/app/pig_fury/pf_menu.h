enum pf_menu_anim_dir : uint8_t {
	PF_MENU_ANIM_LEFT,
	PF_MENU_ANIM_RIGHT,
};

enum pf_menu_item_st : uint8_t {
	PF_MENU_GAMEPLAY,
	PF_MENU_CONFIG,
	PF_MENU_ITEM_COUNT,
};

struct pf_menu_item {
	const uint8_t *bitmap;
	pf_menu_icon *icon;
};


class pf_menu {
public:
	pf_menu() = default;
	~pf_menu() = default;
	void init();
	void update();
	void render();
	void move_next_item();
	void move_pre_item();

	// Setter
	void set_dir(pf_menu_anim_dir dir) { dir_ = dir; };

	// Getter
	bool is_animating() {return animating_;}

private:
	void get_render_pos(int16_t &cur_x, int16_t &target_x) const;
	pf_gameplay_icon gameplay_icon_;
	pf_config_icon config_icon_;
	int16_t pos_x_;
	int16_t pos_y_;
	pf_menu_item menu_items_[PF_MENU_ITEM_COUNT] = {
		{ .bitmap = menu_gameplay_bitmap, .icon = &gameplay_icon_},
		{ .bitmap = menu_config_bitmap, .icon = &config_icon_}
	};
	pf_menu_item *cur_menu_item_;
	pf_menu_item *target_menu_item_;
	uint8_t cur_index_;
	uint8_t target_index_;
	int16_t anim_offset_;
	pf_menu_anim_dir dir_;
	bool animating_;
};

