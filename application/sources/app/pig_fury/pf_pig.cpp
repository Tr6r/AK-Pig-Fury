void pf_pig::update_atk() {
	if (atk_st_ == PF_PIG_ATTACK_WEAPON_PICKUP)
	{
		if (atk_dur_tick_ == 0)
		{
			weapon_->set_st(PF_WEAPON_ST_ATTACH);
			update_weapon_attach_pose();
		}
	}
	if (atk_st_ != PF_PIG_ATTACK_NONE) {
		if (atk_dur_tick_ > 0) atk_dur_tick_--;
		else {
			atk_st_ = PF_PIG_ATTACK_NONE;
			if (weapon_) update_weapon_attach_pose();
		}
	}
}

void pf_pig::update_st() {
	switch (pig_st_) {
		case PF_PIG_ST_JUMP: {
			pos_y_ -= PIG_UPDATE_STEP_PIXEL;

			if (pos_y_ <= (PIG_POS_Y - PIG_JUMP_MAX_HEIGHT))
			{
				pos_y_ = PIG_POS_Y - PIG_JUMP_MAX_HEIGHT;
				pig_st_ = PF_PIG_ST_FALL;
			}
			break;
		}
		case PF_PIG_ST_FALL: {
			pos_y_ += PIG_UPDATE_STEP_PIXEL;
			if (pos_y_ >= PIG_POS_Y) {
				pos_y_ = PIG_POS_Y;
				pig_st_ = PF_PIG_ST_NONE;
				atk_st_ = PF_PIG_ATTACK_NONE;
			}
			break;
		}

		default:
			break;
	}
}

void pf_pig::render_st() {
	if (atk_st_ == PF_PIG_ATTACK_NONE)
	{
		switch (pig_st_)
		{
		case PF_PIG_ST_JUMP:
			view_render.drawBitmap(pos_x_, pos_y_, pig_jump_bitmap, PIG_WIDTH, PIG_HEIGHT, WHITE);
			break;
		case PF_PIG_ST_FALL:
			view_render.drawBitmap(pos_x_, pos_y_, pig_fall_bitmap, PIG_WIDTH, PIG_HEIGHT, WHITE);
			break;
		default:
			break;
		}
	}
}

void pf_pig::jump() {
	if (pig_st_ == PF_PIG_ST_FALL) return;
	pig_st_ = PF_PIG_ST_JUMP;
}

bool pf_pig::is_attack_hit_frame() {
	if (weapon_ && atk_st_ != PF_PIG_ATTACK_NONE && PIG_ATK_FRAME_TICK - atk_dur_tick_ <= 3) return true;
	if (atk_st_ != PF_PIG_ATTACK_NONE && PIG_ATK_FRAME_TICK - atk_dur_tick_ <= 2) return true;
	return false;
}

