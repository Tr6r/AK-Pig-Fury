enum pf_wolf_basic_move_st : uint8_t {
	PF_WOLF_BASIC_MOVE_1,
	PF_WOLF_BASIC_MOVE_2,
	PF_WOLF_BASIC_MOVE_3,
	PF_WOLF_BASIC_MOVE_4,
	PF_WOLF_BASIC_MOVE_COUNT
};

enum pf_wolf_basic_atk_st : uint8_t {
	PF_WOLF_BASIC_ATK_1,
	PF_WOLF_BASIC_ATK_2,
	PF_WOLF_BASIC_ATK_3,
	PF_WOLF_BASIC_ATK_4,
	PF_WOLF_BASIC_ATK_COUNT
};

class pf_wolf_basic : public pf_enemy {
public:
	pf_wolf_basic() {hp_ = 0; st_ = PF_ENEMY_ST_DEAD;}
	~pf_wolf_basic() override = default;

	void init(pf_char_dir dir) override;
	void get_hand_pos(int8_t &pos_x, int8_t &pos_y) override;
	void update() override;
	void render() override;
	void attack() override;
	void take_damage() override;

	// Helper
	inline void update_move_state() {
		if (anim_duration_tick_ > 0) anim_duration_tick_ --;
		if(anim_duration_tick_ == 0) {
			move_st_ = static_cast<pf_wolf_basic_move_st>((static_cast<uint8_t>(move_st_) + 1) % PF_WOLF_BASIC_MOVE_COUNT);
			anim_duration_tick_ = PF_WOLF_BASIC_MOVE_FRAME_TICK;
		}
	}

	inline void update_atk_state() {
		if (anim_duration_tick_ > 0) anim_duration_tick_ --;
		if(anim_duration_tick_ == 0) {
			atk_st_ = static_cast<pf_wolf_basic_atk_st>((static_cast<uint8_t>(atk_st_) + 1) % PF_WOLF_BASIC_ATK_COUNT);
			anim_duration_tick_ = (atk_st_ == PF_WOLF_BASIC_ATK_2 || atk_st_ == PF_WOLF_BASIC_ATK_4) ? PF_WOLF_BASIC_ATK_FRAME_TICK : PF_WOLF_BASIC_ATK_COOLDOWN_FRAME_TICK;
		}
	}
private:
	void update_hit();
	void update_move();
	void update_attack();
	void update_dead();
	void update_knockback();
	void render_hit();
	void render_move();
	void render_attack();
	void render_knockback();
	void render_dead();
	void update_weapon();

	pf_axe axe_; //temp
};

