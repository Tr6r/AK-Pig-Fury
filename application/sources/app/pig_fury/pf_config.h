enum pf_config_item : uint8_t {
	PF_CONFIG_GAME_MODE,
	PF_CONFIG_GAME_SOUND,
	PF_CONFIG_EXIT,
	PF_CONFIG_ITEM_COUNT,
};

enum pf_game_mpde : uint8_t {
	PF_GAME_MODE_NORMAL,
	PF_GAME_MODE_HARD,
	PF_GAME_MODE_COUNT
};

struct pf_config_data {
	pf_game_mpde game_mode;
	bool sound;
};

class pf_config
{
public:
	pf_config() = default;
	~pf_config() = default;

	void init();
	void render();
	void update();
	void move_down();
	void move_up();
	void change_config();
	void save_config();
	void load_config();

	// getter
	pf_config_item get_cur_item() { return cur_item_; }
	pf_config_data get_config_data() { return data_; }
    bool is_sound_enable() { return data_.sound; }

private:
 	pf_config_item cur_item_;
	pf_config_data data_;
	bool is_visible_;
	uint8_t anim_duration_ticks;
};

